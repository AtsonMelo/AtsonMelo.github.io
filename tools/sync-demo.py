"""Vendors the DevLab Phone NUI (HTML/CSS/JS) into demo/phone/ and wires the in-browser simulator.

Single source of truth stays in the private repo. The copy is generated from a COMMIT (never from a
working tree with uncommitted edits) and is never hand-edited. Every deviation from the source is listed
in PATCHES below, asserted at build time and recorded in demo/phone/SOURCE.txt.

  python tools/sync-demo.py --src <fivem-lab> [--rev <commit>]   regenerate demo/phone
  python tools/sync-demo.py --src <fivem-lab> --check [--rev ..]  fail if demo/phone differs from a fresh build

Publishing demo/phone/ makes the phone's NUI frontend source public: review before every publish."""
import argparse, io, pathlib, shutil, subprocess, sys, tarfile, tempfile

root = pathlib.Path(__file__).resolve().parents[1]
WEB = "resources/devlab_phone/web"

# (file, original text, replacement, why). Anything not listed here is byte-identical to the source.
PATCHES = [
    ("js/screens/vehicles.js", "Criando e verificando no jogo…", "Simulando a chamada (sem jogo)…", "UI claimed an in-game result"),
    ("js/screens/vehicles.js", "confirmado no jogo e marcado no mapa. Entre e dirija!", "confirmado (resposta simulada). No jogo, o servidor cria e verifica o veículo real.", "UI claimed an in-game result"),
    ("js/screens/vehicles.js", "name: 'Bugatti Chiron'", "name: 'Supercarro (demo)'", "display name only; vehicle id/model untouched, no trademark in a public demo"),
    ("js/screens/home.js", "'Bugatti Chiron'", "'Supercarro (demo)'", "display name only"),
    ("index.html", "connect-src 'self' https:", "connect-src 'self'; base-uri 'none'; form-action 'none'; object-src 'none'", "tighter CSP: the demo never needs the network"),
    ("index.html", "<title>DevLab Phone</title>", "<title>DevLab Phone — browser demo (simulated)</title>", "title"),
    ("index.html", "</head>", '  <link rel="stylesheet" href="demo.css">\n</head>', "demo-only stylesheet"),
    ("index.html", '<script type="module" src="js/main.js"></script>', '<script src="sim.js"></script>\n  <script type="module" src="js/main.js"></script>', "in-browser FiveM stand-in, loaded first"),
]
ADDED = ["sim.js", "demo.css"]  # copied from tools/demo/


def git(src, *args, binary=False):
    r = subprocess.run(["git", "-C", str(src), *args], capture_output=True)
    if r.returncode: sys.exit(f"git {' '.join(args)} failed: {r.stderr.decode(errors='replace').strip()}")
    return r.stdout if binary else r.stdout.decode().strip()


def build(dst, src, rev):
    data = git(src, "archive", rev, WEB, binary=True)
    with tempfile.TemporaryDirectory() as t:
        tarfile.open(fileobj=io.BytesIO(data)).extractall(t, filter="data")
        shutil.copytree(pathlib.Path(t) / WEB, dst)
    for name in ADDED: shutil.copy(root / "tools" / "demo" / name, dst / name)
    for rel, old, new, _ in PATCHES:
        f = dst / rel; txt = f.read_text(encoding="utf-8")
        if old not in txt: sys.exit(f"patch anchor missing in {rel}: {old!r} (source changed; review PATCHES)")
        f.write_text(txt.replace(old, new, 1), encoding="utf-8")
    full = git(src, "rev-parse", rev)
    lines = [f"NUI snapshot of {WEB} from fivem-lab commit {full[:7]} (committed state only).",
             "Generated by tools/sync-demo.py. Do not edit by hand; verify with: tools/sync-demo.py --check.",
             f"Added files: {', '.join(ADDED)}. Scripted deviations from the source:"]
    lines += [f"  - {rel}: {why}" for rel, _, _, why in PATCHES]
    (dst / "SOURCE.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return full


def norm(p): return p.read_bytes().replace(b"\r\n", b"\n")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", required=True); ap.add_argument("--rev", default="HEAD"); ap.add_argument("--check", action="store_true")
    a = ap.parse_args(); src = pathlib.Path(a.src)
    live = root / "demo" / "phone"
    if a.check:
        with tempfile.TemporaryDirectory() as t:
            fresh = pathlib.Path(t) / "phone"; full = build(fresh, src, a.rev)
            fa = {p.relative_to(fresh).as_posix() for p in fresh.rglob("*") if p.is_file()}
            fb = {p.relative_to(live).as_posix() for p in live.rglob("*") if p.is_file()} if live.exists() else set()
            bad = sorted(fa ^ fb) + sorted(f for f in fa & fb if f != "SOURCE.txt" and norm(fresh / f) != norm(live / f))
            rec = (live / "SOURCE.txt").read_text(encoding="utf-8").split("commit ")[1][:7] if (live / "SOURCE.txt").exists() else "?"
            if bad: sys.exit(f"DRIFT: demo/phone differs from a fresh build of {full[:7]}: {bad}")
            print(f"demo/phone matches a fresh build of {full[:7]} (recorded: {rec})")
    else:
        if live.exists(): shutil.rmtree(live)
        full = build(live, src, a.rev)
        print("demo/phone ready from commit", full[:7])
