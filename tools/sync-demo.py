"""Vendors the DevLab Phone NUI (HTML/CSS/JS) into demo/phone/ and wires the in-browser simulator.
Single source of truth stays in the private repo; the copy is regenerated, never hand-edited.
Usage:  python tools/sync-demo.py --src <path to fivem-lab>
Review before every publish: this copies the NUI frontend source into this (public) repo."""
import argparse, pathlib, shutil, subprocess, datetime, sys

ap = argparse.ArgumentParser(); ap.add_argument("--src", required=True); a = ap.parse_args()
root = pathlib.Path(__file__).resolve().parents[1]
web = pathlib.Path(a.src) / "resources" / "devlab_phone" / "web"
if not (web / "index.html").is_file(): sys.exit(f"not found: {web}")
dst = root / "demo" / "phone"
if dst.exists(): shutil.rmtree(dst)
shutil.copytree(web, dst)
shutil.copy(root / "tools" / "demo" / "sim.js", dst / "sim.js")
shutil.copy(root / "tools" / "demo" / "demo.css", dst / "demo.css")

idx = dst / "index.html"; html = idx.read_text(encoding="utf-8")
anchors = ('</head>', '<script type="module" src="js/main.js"></script>')
if not all(x in html for x in anchors): sys.exit("index.html anchors changed; update sync-demo.py")
html = html.replace('</head>', '  <link rel="stylesheet" href="demo.css">\n</head>', 1)
html = html.replace(anchors[1], '<script src="sim.js"></script>\n  ' + anchors[1], 1)
html = html.replace("<title>DevLab Phone</title>", "<title>DevLab Phone — browser demo (simulated)</title>", 1)
idx.write_text(html, encoding="utf-8")

rev = subprocess.run(["git", "-C", a.src, "rev-parse", "--short", "HEAD"], capture_output=True, text=True).stdout.strip()
(dst / "SOURCE.txt").write_text(f"NUI snapshot of devlab_phone/web from fivem-lab @ {rev}, {datetime.date.today()}.\nGenerated by tools/sync-demo.py. Do not edit by hand.\n", encoding="utf-8")
print("demo/phone ready, source", rev)
